'use strict';
const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const index=read('index.php');
const nav=read('js/next/navigation_core.js');
const mb=read('js/next/mobile_back.js');
const css=read('css/next/mobile_brand_center.css');
const inner=read('css/next/master_responsive_shell.css');
const boot=read('css/runtime_boot_bundle.css');
const shell=read('js/boot/runtime_shell_bundle.js');
assert(index.includes('k-brand-text-fallback')&&index.includes("assets/onboarding/kareta_logo_icon.png"));
assert(index.includes("asset_ver('assets/logo/main/kareta_logo_full.png')"));
assert(nav.includes("anonymous: Object.freeze(['home','services','works','masters','parts','__more__'])"));
assert(nav.includes("'organization_store','anonymous'].includes(kind) ? 6 : 5"));
assert(mb.includes("window.matchMedia?.('(max-width: 599px)')?.matches === true"));
assert(mb.includes("cleanHash !== HOME || phoneNav"));
assert(mb.includes("window.addEventListener('resize', sync"));
assert(shell.includes("cleanHash !== HOME || phoneNav"),'generated JS must contain mobile FAB fix');
assert(shell.includes("['home','services','works','masters','parts','__more__']"),'generated JS must contain guest services');
assert(css.includes('FIX-PROMPT v4')&&boot.includes('FIX-PROMPT v4'));
assert(boot.includes(css.trimEnd()),'boot CSS must contain mobile brand canonical source');
assert(boot.trimEnd().endsWith(inner.trimEnd()),'boot CSS must end with last source');
assert(inner.includes('data-kareta-header-mode="inner"'),'keep inner Back/title contract');
assert(css.includes('data-kareta-header-mode="home"'),'home header explicitly scoped');
assert(css.includes('#k-shell-header .k-brand-logo[hidden]'));
const img=fs.readFileSync(path.join(root,'assets/logo/main/kareta_logo_full.png'));
assert.deepEqual([...img.subarray(0,8)],[137,80,78,71,13,10,26,10]);
// Execute real navigation core in an anonymous context; this is not just a string check.
const vm=require('node:vm');
const routeKeys=['home','services','works','masters','parts'];
const registry={has:k=>routeKeys.includes(k),get:k=>({path:'#/'+k,label:k})};
const dynamic={canAccess:k=>routeKeys.includes(k),items:()=>routeKeys,menuSections:()=>[],defaultRoute:()=> 'home'};
const guestWindow={KaretaRouteRegistry:registry,KaretaDynamicNavigation:dynamic,
  KaretaIdentity:{snapshot:()=>({authenticated:false})},addEventListener:()=>{}};
vm.runInNewContext(nav,{window:guestWindow,document:{documentElement:{dataset:{}}},location:{hash:'#/home'},console});
assert.equal(guestWindow.KaretaNavigationCore.contextKind(),'anonymous');
assert.deepEqual(Array.from(guestWindow.KaretaNavigationCore.mobileItems()),[...routeKeys,'__more__']);
assert(css.includes('html[data-user-role="guest"] #k-mobile-nav .k-nav-label'));
console.log('PASS KARETA phone shell v4: logo fallback, guest 6, no FAB overlap, home/inner contract, bundles');
